def get_fines():
    """Barcha jarimalarni hisoblangan narxi va 50% chegirmasi bilan qaytaradi."""
    result = []
    for item in FINES:
        amount = int(item["bhm"] * BHM)
        discount_50 = int(amount * 0.5)
        result.append({
            **item,
            "bhm_str": f"{item['bhm']} BHM",
            "amount": amount,
            "amount_fmt": f"{amount:,}".replace(",", " "),
            "discount_50": discount_50,
            "discount_50_fmt": f"{discount_50:,}".replace(",", " "),
        })
    return result
